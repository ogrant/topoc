def resolve(file: syntax.SourceFile, context: Context | None) -> ResolvedSystem:
    """Expand loops over data against `context`, bind names, resolve attributes,
    expand loops over instances, fan the topology out to per-instance placements
    and edges, and run the validation checks. `context` is the generation
    context, supplied exactly when the file declares a `context` block. Raises
    `CompileError` on the first violation, or `ContextError` for context data
    that does not fit its declaration."""
    resolver = _Resolver(expand_data(file, context))
    # Each topology block argument, by its location, which it keeps wherever
    # its block's statements were inlined and through expansion (V32).
    for block_use in file.block_uses:
        for argument in block_use.arguments:
            resolver.arguments[argument.value.location] = (argument, block_use.block)
    return resolver.run()


def compile_topology(source: str, context: Context | None) -> ResolvedSystem:
    """Parse and resolve `.topo` source in one step: the common entry point."""
    return resolve(parse(source), context)


