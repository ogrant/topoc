# A name an identifier could spell: `.`-separated segments, each a letter or
# `_` followed by letters, digits or `_`.
_VALID_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*")


@dataclass(frozen=True, slots=True)
class _TopicSlot:
    """A topic in source order: a topic (hand-written or generated by a loop over
    data) or a loop over instances, with the names as written and the
    iterations that generated it."""

    definition: syntax.TopicDef | syntax.ForDef
    name_templates: list[str]
    origin: Origin | None


# `(topic, statement-level peer label, filter)`. V9 compares these across group
# members: statement-level labels make the comparison independent of which
# concrete peer an edge landed on (a mesh edge Infra1 -> Infra2 and its mirror
# image are the same configuration).
type _EdgeView = tuple[str, str, str | None]


@dataclass(slots=True)
class _InstanceState:
    """Everything the resolver accumulates for one instance."""

    definition: syntax.InstanceDef
    # The iterations that generated the instance, if a loop did.
    origin: Origin | None
    roles: list[str] = field(default_factory=list)
    group: str = ""
    attrs: dict[AttrKey, AttrValue] = field(default_factory=dict)
    placements: set[str] = field(default_factory=set)
    # The registry: each topic or queue name the instance hosts and the
    # declaration whose copy it is (an index into the resolver's declarations).
    hosts: dict[str, int] = field(default_factory=dict)
    destinations: list[Destination] = field(default_factory=list)
    incoming: list[Incoming] = field(default_factory=list)
    sows: list[ResolvedSow] = field(default_factory=list)
    out_view: set[_EdgeView] = field(default_factory=set)
    in_view: set[_EdgeView] = field(default_factory=set)

    @property
    def name(self) -> str:
        return self.definition.name.text


@dataclass(frozen=True, slots=True)
class _Declaration:
    """A topic or queue declaration, hand-written or generated, as the
    per-instance registry refers to it."""

    kind: str  # `topic` or `queue`
    name: syntax.Ident
    origin: Origin | None

    def whereabouts(self) -> str:
        """Where it is declared, for an error raised by another declaration."""
        generated = (
            ""
            if self.origin is None
            else f" (from the 'for' at line {self.origin.loop.line}, column "
            f"{self.origin.loop.column} with {self.origin.bindings_text()})"
        )
        return (
            f"the {self.kind} declared at line {self.name.location.line}, column "
            f"{self.name.location.column}{generated}"
        )


@dataclass(frozen=True, slots=True)
class _InstanceSet:
    """A topology name resolved to the instances it denotes, in declaration order."""

    kind: NameKind
    members: list[int]


def _with_article(word: str) -> str:
    """`word` with its indefinite article: `a role`, `an instance`."""
    return f"{'an' if word[0] in 'aeiou' else 'a'} {word}"


def _type_name(literal: syntax.Literal) -> str:
    # `bool` is a subclass of `int`, so it must be tested first.
    if isinstance(literal, bool):
        return "bool"
    if isinstance(literal, int):
        return "int"
    return "string"


def _to_model(durability: syntax.Durability) -> Durability:
    match durability:
        case syntax.PersistentDurability(file):
            return PersistentDurability(file.value)
        case syntax.TransientDurability(recovery_point):
            return TransientDurability(RecoveryPoint(recovery_point.value))


def _fail(message: str, at: SourceLocation) -> NoReturn:
    raise CompileError.at(message, at)


def _check_name(name: syntax.Ident, kind: str) -> None:
    """Instance and group names become environment variable and service names,
    so a quoted one must still spell an identifier (V25)."""
    if not _VALID_NAME.fullmatch(name.text):
        _fail(
            f"'{name.text}' is not a valid {kind} name ('.'-separated segments of letters, "
            "digits and '_', each starting with a letter or '_')",
            name.location,
        )


