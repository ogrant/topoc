class _Resolver:
    """Resolves one source file. Also serves as the expander's `ExpansionContext`."""

    def __init__(self, items: list[Item]) -> None:
        """Phase 1: build the flat namespace (V1) and type-check role attribute
        defaults (V10 for defaults), over the definitions data expansion left."""
        self._names: dict[str, NameEntry] = {}
        # Topology block arguments, by their location, with their block.
        self.arguments: dict[SourceLocation, tuple[syntax.Argument, syntax.Ident]] = {}
        self._roles: dict[str, syntax.RoleDef] = {}
        self._topic_slots: list[_TopicSlot] = []
        self._topics: list[ExpandedTopic] = []
        self._instances: list[_InstanceState] = []
        self._instance_index: dict[str, int] = {}
        # Explicit groups only, in order of first mention; members in
        # declaration order.
        self._groups: dict[str, list[int]] = {}
        # Every queue in source order: hand-written, or generated by a loop (over
        # data, then over instances as `_expand_topics` reaches it).
        self._queue_defs: list[ExpandedQueue] = []
        # Names of the queues, whose placements and edges share the topics'
        # tables (names are unique across both) until `_build` separates them.
        self._queue_names: set[str] = set()
        # Every topic and queue declaration resolved so far, in order; the last
        # one is being resolved.
        self._declarations: list[_Declaration] = []

        for item in items:
            definition, origin = item.definition, item.origin
            match definition:
                case syntax.RoleDef():
                    self._declare(definition.name, NameKind.ROLE)
                    _check_defaults(definition)
                    self._roles[definition.name.text] = definition
                case syntax.TopicDef():
                    try:
                        self._declare_shared(definition.name, NameKind.TOPIC)
                    except CompileError as error:
                        raise annotated(error, origin, "topic", definition.name.text) from error
                    self._topic_slots.append(_TopicSlot(definition, item.name_templates, origin))
                case syntax.QueueDef():
                    try:
                        self._declare_shared(definition.name, NameKind.QUEUE)
                    except CompileError as error:
                        raise annotated(error, origin, "queue", definition.name.text) from error
                    template = (
                        item.name_templates[0] if item.name_templates else definition.name.text
                    )
                    self._queue_defs.append(ExpandedQueue(definition, template, origin))
                    self._queue_names.add(definition.name.text)
                case syntax.InstanceDef():
                    try:
                        _check_name(definition.name, "instance")
                        if definition.group is not None:
                            _check_name(definition.group, "group")
                        self._declare(definition.name, NameKind.INSTANCE)
                    except CompileError as error:
                        raise annotated(error, origin, "instance", definition.name.text) from error
                    self._instance_index[definition.name.text] = len(self._instances)
                    self._instances.append(_InstanceState(definition, origin))
                case syntax.ListDef():
                    self._declare(definition.name, NameKind.LIST)
                case syntax.ForDef():
                    self._topic_slots.append(_TopicSlot(definition, item.name_templates, origin))
                case syntax.TopologyDef():
                    self._declare(definition.name, NameKind.TOPOLOGY)
                case syntax.ContextDef():
                    pass

    def run(self) -> ResolvedSystem:
        for instance in self._instances:
            try:
                self._resolve_instance(instance)
            except CompileError as error:
                raise annotated(error, instance.origin, "instance", instance.name) from error
        self._topics = self._expand_topics()
        topics = self._resolve_topics()
        self._check_shared_definitions(0, [topic.definition for topic in topics])
        queues = self._resolve_queues(topics)
        self._check_shared_definitions(len(topics), [queue.definition for queue in queues])
        self._check_group_consistency()
        self._compute_passthrough()
        return self._build(topics, queues)

    # ---- ExpansionContext ---------------------------------------------------

    def lookup(self, name: str) -> NameEntry | None:
        return self._names.get(name)

    def instances_of(self, name: syntax.Ident) -> list[str]:
        return [self._instances[ix].name for ix in self._resolve_set(name).members]

    def attribute(self, instance: str, key: AttrKey) -> AttrValue | None:
        return self._instances[self._instance_index[instance]].attrs.get(key)

    # ---- phase 1 ------------------------------------------------------------

    def _declare(self, name: syntax.Ident, kind: NameKind) -> None:
        if (first := self._names.get(name.text)) is not None:
            _fail(
                f"name '{name.text}' already defined as {first.kind.value} at line "
                f"{first.location.line}, column {first.location.column}",
                name.location,
            )
        self._names[name.text] = NameEntry(kind, name.location)

    def _declare_shared(self, name: syntax.Ident, kind: NameKind) -> None:
        """Declare a topic or queue name. Several declarations may share one,
        each placing its own copy on other instances (the per-instance registry
        checks that, see `_place`), but a name is of one kind throughout (V1)."""
        existing = self._names.get(name.text)
        if existing is None or existing.kind is not kind:
            self._declare(name, kind)

    # ---- the per-instance registry ------------------------------------------

    def _begin(self, kind: str, name: syntax.Ident, origin: Origin | None) -> None:
        """Start resolving a topic or queue declaration."""
        self._declarations.append(_Declaration(kind, name, origin))

    def _current(self) -> int:
        """The declaration being resolved."""
        return len(self._declarations) - 1

    def _hosts_current(self, instance: _InstanceState, name: str) -> bool:
        """Whether `instance` hosts the copy of `name` the declaration being
        resolved places."""
        return instance.hosts.get(name) == self._current()

    def _current_instances(self, name: str) -> list[str]:
        """The instances hosting the declaration being resolved, in order."""
        return [i.name for i in self._instances if self._hosts_current(i, name)]

    def _place(self, name: str, members: list[int], at: SourceLocation) -> None:
        """Place the declaration being resolved's copy of `name` on `members`.
        An instance hosts one topic or queue of each name, so another
        declaration having placed it there already is an error, whichever
        statements placed either; in particular, replication cannot link two
        declarations' copies."""
        current = self._current()
        declaration = self._declarations[current]
        if declaration.name.text != name:
            # A queue's source topic, carried between its domains (lab F24): its
            # own declaration places it, and the queue's holders must host it.
            return
        for ix in members:
            instance = self._instances[ix]
            other = instance.hosts.get(name)
            if other is not None and other != current:
                _fail(
                    f"{declaration.kind} '{name}' is already on instance '{instance.name}', "
                    f"placed by {self._declarations[other].whereabouts()}: an instance hosts "
                    "one topic or queue of each name",
                    at,
                )
            instance.hosts[name] = current
            instance.placements.add(name)

    def _check_shared_definitions(self, first: int, definitions: list[str]) -> None:
        """Every declaration of a name shares its definition, so the name has
        one message type and field names wherever it lives. `definitions` are
        those of the declarations from `first` on, in order."""
        seen: dict[str, tuple[int, str]] = {}
        for ix, definition in enumerate(definitions, start=first):
            declaration = self._declarations[ix]
            name = declaration.name.text
            if name not in seen:
                seen[name] = (ix, definition)
                continue
            other, shared = seen[name]
            if shared != definition:
                kind = declaration.kind
                try:
                    _fail(
                        f"{kind} '{name}' has definition '{definition}' here but '{shared}' in "
                        f"{self._declarations[other].whereabouts()}: every declaration of a "
                        "name shares its definition",
                        declaration.name.location,
                    )
                except CompileError as error:
                    raise annotated(error, declaration.origin, kind, name) from error

    # ---- phase 2: roles, group membership, attributes (V2, V5-V7, V10) -----

    def _resolve_instance(self, instance: _InstanceState) -> None:
        instance.roles = self._resolve_roles(instance.definition)
        instance.group = self._resolve_group(instance)
        instance.attrs = self._resolve_attrs(instance.definition, instance.roles)

    def _resolve_roles(self, instance: syntax.InstanceDef) -> list[str]:
        carried: list[str] = []
        for role in instance.roles:
            entry = self._names.get(role.text)
            if entry is None:
                _fail(f"unknown role '{role.text}'", role.location)
            if entry.kind is not NameKind.ROLE:
                _fail(f"'{role.text}' is a {entry.kind.value}, expected a role", role.location)
            if role.text in carried:
                _fail(
                    f"duplicate role '{role.text}' in instance '{instance.name.text}'",
                    role.location,
                )
            carried.append(role.text)
        return carried

    def _resolve_group(self, instance: _InstanceState) -> str:
        """Explicit groups come into existence by being named; an instance
        without a `group` clause is its own singleton group."""
        group = instance.definition.group
        if group is None:
            return instance.name
        entry = self._names.get(group.text)
        if entry is None:
            self._names[group.text] = NameEntry(NameKind.GROUP, group.location)
        elif entry.kind is not NameKind.GROUP:
            _fail(
                f"group name '{group.text}' conflicts with {entry.kind.value} defined at line "
                f"{entry.location.line}, column {entry.location.column}",
                group.location,
            )
        self._groups.setdefault(group.text, []).append(self._instance_index[instance.name])
        return group.text

    def _resolve_attrs(
        self, instance: syntax.InstanceDef, carried: list[str]
    ) -> dict[AttrKey, AttrValue]:
        values: dict[AttrKey, AttrValue] = {}
        for assign in instance.attrs:
            if assign.role.text not in carried:
                _fail(
                    f"instance '{instance.name.text}' does not carry role '{assign.role.text}'",
                    assign.role.location,
                )
            decl = _find_attr(self._roles[assign.role.text], assign.attr.text)
            if decl is None:
                _fail(
                    f"role '{assign.role.text}' declares no attribute '{assign.attr.text}'",
                    assign.attr.location,
                )
            # The data expander binds every placeholder to its value.
            value = assign.value
            if isinstance(value, syntax.Placeholder):
                _fail(
                    f"'{{{{{value.expr}}}}}' names no loop variable or context field",
                    assign.value_location,
                )
            if _type_name(value) != decl.attr_type.value:
                _fail(
                    f"attribute '{assign.role.text}.{assign.attr.text}' expects "
                    f"{decl.attr_type.value}, got {_type_name(value)}",
                    assign.value_location,
                )
            values[AttrKey(assign.role.text, assign.attr.text)] = value

        for role in carried:
            for decl in self._roles[role].attrs:
                key = AttrKey(role, decl.name.text)
                if key in values:
                    continue
                if decl.default is None:
                    _fail(
                        f"instance '{instance.name.text}' missing value for "
                        f"'{role}.{decl.name.text}'",
                        instance.name.location,
                    )
                values[key] = decl.default
        return values

    def _resolve_set(self, name: syntax.Ident) -> _InstanceSet:
        """The instances a topology name denotes (V2, V4), with the name's kind
        so callers can apply kind-specific semantics. A topology block's
        argument must name its parameter's kind (V32)."""
        resolved = self._resolve_name(name)
        found = self.arguments.get(name.location)
        if found is not None:
            argument, block = found
            wanted = {
                syntax.ParamKind.GROUP: NameKind.GROUP,
                syntax.ParamKind.ROLE: NameKind.ROLE,
                syntax.ParamKind.INSTANCE: NameKind.INSTANCE,
            }.get(argument.kind)
            if wanted is not None and resolved.kind is not wanted:
                parameter = argument.parameter.text
                _fail(
                    f"argument '{name.text}' for '{parameter}' of topology block '{block.text}' "
                    f"is {_with_article(resolved.kind.value)}; '{parameter}' takes "
                    f"{_with_article(argument.kind.value)}",
                    name.location,
                )
        return resolved

    def _resolve_name(self, name: syntax.Ident) -> _InstanceSet:
        entry = self._names.get(name.text)
        if entry is None:
            _fail(f"unknown name '{name.text}'", name.location)
        match entry.kind:
            case NameKind.TOPIC | NameKind.QUEUE | NameKind.LIST | NameKind.TOPOLOGY:
                _fail(
                    f"'{name.text}' is a {entry.kind.value}; expected a role, group or instance",
                    name.location,
                )
            case NameKind.ROLE:
                members = [
                    ix for ix, instance in enumerate(self._instances) if name.text in instance.roles
                ]
                if not members:
                    _fail(f"role '{name.text}' has no instances", name.location)
                return _InstanceSet(NameKind.ROLE, members)
            case NameKind.GROUP:
                return _InstanceSet(NameKind.GROUP, self._groups[name.text])
            case NameKind.INSTANCE:
                return _InstanceSet(NameKind.INSTANCE, [self._instance_index[name.text]])

    # ---- phase 3: expansion of loops over instances (V13-V19) --------------

    def _expand_topics(self) -> list[ExpandedTopic]:
        """Every topic in source order, loops over instances expanded in place.
        Their names join the flat namespace here (V1, V16), once groups are
        known."""
        topics: list[ExpandedTopic] = []
        for slot in self._topic_slots:
            if isinstance(slot.definition, syntax.TopicDef):
                topic = slot.definition
                name_template = slot.name_templates[0] if slot.name_templates else topic.name.text
                try:
                    check_topic_name(topic.name)
                except CompileError as error:
                    raise annotated(error, slot.origin, "topic", name_template) from error
                topics.append(ExpandedTopic(topic, name_template, slot.origin))
                continue
            for expanded in expand(slot.definition, self, slot.origin, slot.name_templates):
                if isinstance(expanded, ExpandedQueue):
                    try:
                        self._declare_shared(expanded.queue.name, NameKind.QUEUE)
                    except CompileError as error:
                        raise annotated(
                            error, expanded.origin, "queue", expanded.queue.name.text
                        ) from error
                    self._queue_names.add(expanded.queue.name.text)
                    self._queue_defs.append(expanded)
                    continue
                try:
                    self._declare_shared(expanded.topic.name, NameKind.TOPIC)
                except CompileError as error:
                    raise annotated(
                        error, expanded.origin, "topic", expanded.topic.name.text
                    ) from error
                topics.append(expanded)
        return topics

    # ---- phase 4: topics and topology fan-out (V3, V4, V8, V11) -------------

    def _resolve_topics(self) -> list[ResolvedTopic]:
        resolved: list[ResolvedTopic] = []
        for expanded in self._topics:
            self._begin("topic", expanded.topic.name, expanded.origin)
            try:
                resolved.append(self._resolve_topic(expanded.topic, expanded.name_template))
            except CompileError as error:
                raise annotated(
                    error, expanded.origin, "topic", expanded.topic.name.text
                ) from error
        return resolved

    # ---- phase 5: queues -----------------------------------------------------

    def _resolve_queues(self, topics: list[ResolvedTopic]) -> list[ResolvedQueue]:
        """Queues, after topics (their sources must already be placed). A
        queue's topology fans out exactly like a topic's, under its name."""
        definitions = {topic.name: topic.definition for topic in topics}
        resolved: list[ResolvedQueue] = []
        for expanded in self._queue_defs:
            self._begin("queue", expanded.queue.name, expanded.origin)
            try:
                queue = self._resolve_queue(expanded.queue, definitions)
            except CompileError as error:
                raise annotated(
                    error, expanded.origin, "queue", expanded.queue.name.text
                ) from error
            resolved.append(replace(queue, name_template=expanded.name_template))
        return resolved

    def _resolve_queue(self, queue: syntax.QueueDef, definitions: dict[str, str]) -> ResolvedQueue:
        name = queue.name.text

        def unresolved(text: str, location: SourceLocation) -> None:
            if "{{" in text:
                _fail(
                    f"'{text}' in queue '{name}' contains '{{{{...}}}}', which only context "
                    "data can fill here",
                    location,
                )

        unresolved(name, queue.name.location)
        # AMPS refuses to start with a queue named with regular-expression
        # characters (lab F20).
        forbidden = next((c for c in name if c in _QUEUE_NAME_FORBIDDEN), None)
        if forbidden is not None:
            _fail(
                f"queue name '{name}' contains '{forbidden}': AMPS does not allow "
                f"regular-expression characters ({_QUEUE_NAME_FORBIDDEN}) in a queue's name",
                queue.name.location,
            )

        definition, source = self._resolve_queue_source(name, queue.source, definitions)

        # Topology: which statements it holds decides the queue's kind.
        kind = self._resolve_queue_topology(name, queue)

        # Every instance holding the queue hosts its sources.
        holders = [i for i in self._instances if self._hosts_current(i, name)]
        sources = queue.source.sources if isinstance(queue.source, syntax.QueueTopics) else []
        for holder in holders:
            missing = next((s for s in sources if s.text not in holder.placements), None)
            if missing is not None:
                _fail(
                    f"queue '{name}' is on '{holder.name}', which does not host its source topic "
                    f"'{missing.text}' (place the topic there in its own topology)",
                    missing.location,
                )

        ordering: QueueOrdering | None = None
        match queue.ordering:
            case syntax.Priority(path):
                unresolved(path.value, path.location)
                ordering = Priority(path.value)
            case syntax.Barrier(text):
                unresolved(text.value, text.location)
                ordering = Barrier(text.value)
        if queue.filter is not None:
            unresolved(queue.filter.value, queue.filter.location)
        return ResolvedQueue(
            name=name,
            name_template=name,
            instances=self._current_instances(name),
            definition=definition,
            source=source,
            kind=kind,
            filter=None if queue.filter is None else queue.filter.value,
            delivery=queue.delivery,
            ordering=ordering,
            recovery_point=queue.recovery_point,
            target_depth=queue.target_depth,
            file_backed_metadata=queue.file_backed_metadata,
            deferred_ack_expiration=queue.deferred_ack_expiration,
        )

    def _resolve_queue_topology(self, name: str, queue: syntax.QueueDef) -> QueueKind:
        """Fan out a queue's topology, and the AMPS element it makes: `local`
        places a `LocalQueue`, `mesh` and `replicate ... <-> ...` a `Queue`,
        `owned by` blocks a `GroupLocalQueue` with one domain per block. Between
        domains, two-way statements carry only the queue's sources (lab F24)."""
        locals_: list[syntax.LocalStmt] = []
        meshes: list[syntax.MeshStmt] = []
        links: list[syntax.ReplicateStmt] = []
        blocks: list[syntax.OwnedStmt] = []
        for statement in queue.topology:
            match statement:
                case syntax.SowStmt(target=target):
                    _fail(
                        f"queue '{name}': a queue's topology takes 'mesh', 'replicate ... <-> "
                        "...', 'local' or 'owned by', not 'sow' (a queue is not materialised in a "
                        "SOW)",
                        target.location,
                    )
                case syntax.ReplicateStmt(two_way=False, source=source):
                    _fail(
                        f"queue '{name}': a replicated queue must be replicated both ways (AMPS "
                        "requires it): write 'replicate ... <-> ...'",
                        source.location,
                    )
                case syntax.LocalStmt():
                    locals_.append(statement)
                case syntax.MeshStmt():
                    meshes.append(statement)
                case syntax.ReplicateStmt():
                    links.append(statement)
                case syntax.OwnedStmt():
                    blocks.append(statement)

        if locals_:
            if meshes or links or blocks:
                _fail(
                    f"queue '{name}': 'local' places an independent queue on each instance (a "
                    "LocalQueue), which AMPS refuses to replicate; it cannot also take 'mesh', "
                    "'replicate' or 'owned by'",
                    locals_[0].target.location,
                )
            for local in locals_:
                self._place(name, self._resolve_set(local.target).members, local.target.location)
            return LocalQueue()
        if not blocks:
            for mesh in meshes:
                self._fan_out_mesh(name, mesh)
            for link in links:
                self._fan_out_replicate(name, link)
            return DistributedQueue()
        if meshes:
            group = meshes[0].group
            _fail(
                f"queue '{name}' is owned, so 'mesh {group.text}' belongs inside an 'owned by' "
                "block (a queue cannot be partly owned)",
                group.location,
            )

        domains: list[QueueDomain] = []
        domain_of: dict[int, str] = {}
        for block in blocks:
            owner = block.owner
            if owner.location in self.arguments:
                # A topology block's argument: checked against its kind (V32).
                self._resolve_set(owner)
            if any(domain.owner == owner.text for domain in domains):
                _fail(
                    f"'{owner.text}' already owns a block of queue '{name}'; write its statements "
                    "in one 'owned by' block",
                    owner.location,
                )
            members: set[int] = set()
            for inner in block.statements:
                match inner:
                    case syntax.MeshStmt(group):
                        members.update(self._resolve_set(group).members)
                        self._fan_out_mesh(name, inner)
                    case syntax.ReplicateStmt(source=source, target=target):
                        members.update(self._resolve_set(source).members)
                        members.update(self._resolve_set(target).members)
                        self._fan_out_replicate(name, inner)
            if all(self._instances[ix].name != owner.text for ix in members):
                _fail(
                    f"the owner of an 'owned by' block of queue '{name}' must be an instance it "
                    f"places; '{owner.text}' is not",
                    owner.location,
                )
            for ix in sorted(members):
                other = domain_of.setdefault(ix, owner.text)
                if other != owner.text:
                    _fail(
                        f"instance '{self._instances[ix].name}' is in two domains of queue "
                        f"'{name}' (owned by '{other}' and '{owner.text}')",
                        owner.location,
                    )
            domains.append(
                QueueDomain(owner.text, sorted(self._instances[ix].name for ix in members))
            )

        # Links between domains: only the data crosses (lab F21, F24).
        for link in links:
            sources = self._resolve_set(link.source).members
            targets = self._resolve_set(link.target).members
            for ix in [*sources, *targets]:
                if ix not in domain_of:
                    _fail(
                        f"'replicate {link.source.text} <-> {link.target.text}' links domains of "
                        f"queue '{name}', but '{self._instances[ix].name}' is in none: place it in "
                        "an 'owned by' block",
                        link.source.location,
                    )
            for a in sources:
                for b in targets:
                    if domain_of[a] == domain_of[b]:
                        _fail(
                            f"'replicate {link.source.text} <-> {link.target.text}' links "
                            f"instances of the same domain of queue '{name}' (owned by "
                            f"'{domain_of[a]}'): put it inside its 'owned by' block",
                            link.source.location,
                        )
            if isinstance(queue.source, syntax.QueueTopics):
                for topic in queue.source.sources:
                    self._fan_out_replicate(topic.text, link)
            else:
                # The queue's own name is its data.
                self._fan_out_replicate(name, link)
        return GroupLocalQueue(sorted(domains, key=lambda domain: domain.owner))

    def _resolve_queue_source(
        self, name: str, source: syntax.QueueSource, definitions: dict[str, str]
    ) -> tuple[str, QueueSource]:
        """What queue `name` reads, and the definition giving it its contract:
        declared topics sharing one definition (with `publish_to` one of them,
        required for several), or the topic of its own name."""
        if isinstance(source, syntax.QueueOwnName):
            return source.definition.text, QueueOwnName()
        first: tuple[syntax.Ident, str] | None = None
        for topic in source.sources:
            entry = self._names.get(topic.text)
            if entry is None:
                _fail(f"unknown name '{topic.text}'", topic.location)
            if entry.kind is not NameKind.TOPIC:
                _fail(
                    f"'{topic.text}' is a {entry.kind.value}; a queue reads from topics",
                    topic.location,
                )
            this = definitions[topic.text]
            if first is None:
                first = (topic, this)
            elif first[1] != this:
                _fail(
                    f"queue '{name}' reads from topics of different definitions: "
                    f"'{first[0].text}' is '{first[1]}' and '{topic.text}' is '{this}'",
                    topic.location,
                )
        assert first is not None, "the parser requires at least one source"
        if source.publish_to is not None:
            if all(topic.text != source.publish_to.text for topic in source.sources):
                _fail(
                    f"'publish_to' must name one of queue '{name}''s sources, not "
                    f"'{source.publish_to.text}'",
                    source.publish_to.location,
                )
        elif len(source.sources) > 1:
            _fail(
                f"queue '{name}' reads from several topics, so it requires 'publish_to': the "
                f"source that publishes to '{name}' itself land on",
                source.sources[0].location,
            )
        publish_to = None if source.publish_to is None else source.publish_to.text
        return first[1], QueueTopics([topic.text for topic in source.sources], publish_to)

    def _resolve_topic(self, topic: syntax.TopicDef, name_template: str) -> ResolvedTopic:
        if topic.definition is None:
            _fail(f"topic '{topic.name.text}' is missing 'definition'", topic.name.location)
        if topic.topology is None:
            _fail(f"topic '{topic.name.text}' is missing 'topology'", topic.name.location)

        name = topic.name.text
        # Placement and replication first, so `sow` targets can be checked
        # against the topic's completed placement.
        for statement in topic.topology:
            match statement:
                case syntax.MeshStmt():
                    self._fan_out_mesh(name, statement)
                case syntax.LocalStmt():
                    target = statement.target
                    self._place(name, self._resolve_set(target).members, target.location)
                case syntax.ReplicateStmt():
                    self._fan_out_replicate(name, statement)
                case syntax.SowStmt():
                    pass
                case syntax.OwnedStmt(owner=owner):
                    _fail(
                        f"'owned by {owner.text}' applies to queues only: a topic has no owner",
                        owner.location,
                    )
        for statement in topic.topology:
            if isinstance(statement, syntax.SowStmt):
                self._materialise(name, statement)
        return ResolvedTopic(
            name, name_template, topic.definition.text, self._current_instances(name)
        )

    def _fan_out_mesh(self, topic: str, mesh: syntax.MeshStmt) -> None:
        """`mesh G`: every member hosts the topic and replicates to every other."""
        group = self._resolve_set(mesh.group)
        if group.kind is not NameKind.GROUP:
            _fail(
                f"'mesh' requires a group; '{mesh.group.text}' is a {group.kind.value}",
                mesh.group.location,
            )
        self._place(topic, group.members, mesh.group.location)
        view: _EdgeView = (topic, mesh.group.text, None)
        for source_ix in group.members:
            source = self._instances[source_ix]
            for target_ix in group.members:
                if target_ix == source_ix:
                    continue
                target = self._instances[target_ix]
                source.destinations.append(
                    Destination(topic, EdgeKind.MESH, mesh.group.text, [target.name], None, [])
                )
                source.out_view.add(view)
                target.incoming.append(Incoming(topic, source.name, None))
                target.in_view.add(view)

    def _fan_out_replicate(self, topic: str, edge: syntax.ReplicateStmt) -> None:
        """`replicate S -> T [where F]`: the kind of T decides the shape.
        `replicate A <-> B [where F]` is one two-way edge each way, both
        filtered by F."""
        if edge.two_way:
            if edge.filter is not None:
                self._check_two_way_filter(topic, edge, edge.filter)
            reverse = syntax.ReplicateStmt(edge.target, edge.source, edge.filter, two_way=True)
            for one_way in (edge, reverse):
                self._fan_out_one_way(topic, one_way, EdgeKind.TWO_WAY)
        else:
            self._fan_out_one_way(topic, edge, EdgeKind.REPLICATE)

    def _check_two_way_filter(
        self, topic: str, edge: syntax.ReplicateStmt, filter_text: syntax.StringLit
    ) -> None:
        """AMPS requires both directions of a two-way pair to replicate a topic
        with the same filter (its `replicate_filter` check), so the filter must
        render identically for every instance on either side: a `{{Role.attr}}`
        taking each target's value would differ by direction."""
        first: tuple[str, str] | None = None
        for side in (edge.target, edge.source):
            instances = self._resolve_set(side)
            for member in instances.members:
                rendered = self._interpolate(filter_text, member, side, instances.kind)
                name = self._instances[member].name
                if first is None:
                    first = (name, rendered)
                elif first[1] != rendered:
                    _fail(
                        f"a two-way 'replicate' must filter topic '{topic}' the same way in "
                        f"both directions, but its filter renders '{first[1]}' for "
                        f"'{first[0]}' and '{rendered}' for '{name}'",
                        filter_text.location,
                    )

    def _fan_out_one_way(self, topic: str, edge: syntax.ReplicateStmt, kind: EdgeKind) -> None:
        sources = self._resolve_set(edge.source)
        targets = self._resolve_set(edge.target)
        for ix in sources.members:
            if ix in targets.members:
                _fail(
                    f"edge from '{edge.source.text}' to '{edge.target.text}' includes instance "
                    f"'{self._instances[ix].name}' on both sides",
                    edge.target.location,
                )
        self._place(topic, sources.members, edge.source.location)
        self._place(topic, targets.members, edge.target.location)
        if targets.kind is NameKind.GROUP:
            self._replicate_to_group(topic, edge, sources, targets, kind)
        else:
            self._replicate_to_each(topic, edge, sources, targets, kind)

    def _replicate_to_group(
        self,
        topic: str,
        edge: syntax.ReplicateStmt,
        sources: _InstanceSet,
        targets: _InstanceSet,
        kind: EdgeKind,
    ) -> None:
        """Group target: one destination per source, members as failover
        addresses, which requires the filter to render identically for every
        member."""
        rendered: str | None = None
        if edge.filter is not None:
            for member in targets.members:
                candidate = self._interpolate(edge.filter, member, edge.target, targets.kind)
                if rendered is not None and rendered != candidate:
                    _fail(
                        f"members of group '{edge.target.text}' produce conflicting filters "
                        f"for topic '{topic}'",
                        edge.filter.location,
                    )
                rendered = candidate
        member_names = [self._instances[ix].name for ix in targets.members]
        for source_ix in sources.members:
            source = self._instances[source_ix]
            source.destinations.append(
                Destination(topic, kind, edge.target.text, member_names, rendered, [])
            )
            source.out_view.add((topic, edge.target.text, rendered))
            for target_ix in targets.members:
                target = self._instances[target_ix]
                target.incoming.append(Incoming(topic, source.name, rendered))
                target.in_view.add((topic, edge.source.text, rendered))

    def _replicate_to_each(
        self,
        topic: str,
        edge: syntax.ReplicateStmt,
        sources: _InstanceSet,
        targets: _InstanceSet,
        kind: EdgeKind,
    ) -> None:
        """Role and instance targets: one destination per target instance, with
        the filter interpolated against that instance."""
        for target_ix in targets.members:
            target = self._instances[target_ix]
            rendered = (
                None
                if edge.filter is None
                else self._interpolate(edge.filter, target_ix, edge.target, targets.kind)
            )
            for source_ix in sources.members:
                source = self._instances[source_ix]
                source.destinations.append(
                    Destination(topic, kind, target.group, [target.name], rendered, [])
                )
                source.out_view.add((topic, edge.target.text, rendered))
                target.incoming.append(Incoming(topic, source.name, rendered))
                target.in_view.add((topic, edge.source.text, rendered))

    def _materialise(self, topic: str, sow: syntax.SowStmt) -> None:
        """`sow T { durability ... }`: every targeted instance must already host
        the topic."""
        durability = _to_model(sow.durability)
        for ix in self._resolve_set(sow.target).members:
            instance = self._instances[ix]
            if not self._hosts_current(instance, topic):
                _fail(
                    f"'sow {sow.target.text}' for topic '{topic}': instance '{instance.name}' "
                    "does not host the topic (declare its placement with 'mesh', 'local' or "
                    "'replicate' first)",
                    sow.target.location,
                )
            instance.sows.append(ResolvedSow(topic, durability))

    def _interpolate(
        self, filter_lit: syntax.StringLit, target_ix: int, target: syntax.Ident, kind: NameKind
    ) -> str:
        """Expand `{{Role.attr}}` against one target instance (V8). Everything
        else in the string — including `${...}` and `%n` — passes through
        verbatim."""
        instance = self._instances[target_ix]

        def replace(expr: str) -> str:
            role, dot, attr = expr.rpartition(".")
            if not dot:
                _fail(
                    f"interpolation '{{{{{expr}}}}}' must be a qualified 'Role.attr'",
                    filter_lit.location,
                )
            if role not in instance.roles:
                if kind is NameKind.GROUP:
                    message = (
                        f"target of this edge is group '{target.text}'; '{{{{{expr}}}}}' "
                        f"requires targets selected by role '{role}'"
                    )
                else:
                    message = (
                        f"'{{{{{expr}}}}}' requires target instance '{instance.name}' "
                        f"to carry role '{role}'"
                    )
                _fail(message, filter_lit.location)
            value = instance.attrs.get(AttrKey(role, attr))
            if value is None:
                _fail(f"role '{role}' declares no attribute '{attr}'", filter_lit.location)
            return to_text(value)

        rendered = substitute(filter_lit.value, replace)
        if rendered is None:
            _fail("unterminated '{{' in filter", filter_lit.location)
        return rendered

    # ---- V9: group consistency ----------------------------------------------

    def _check_group_consistency(self) -> None:
        """Members of an explicit group must end up with identical placements and
        equivalent incoming/outgoing replication."""
        for group, members in self._groups.items():
            first = self._instances[members[0]]
            for ix in members[1:]:
                member = self._instances[ix]
                if (
                    member.hosts == first.hosts
                    and member.in_view == first.in_view
                    and member.out_view == first.out_view
                ):
                    continue
                topic = _divergent_topic(first, member)
                what = "queue" if topic in self._queue_names else "topic"
                _fail(
                    f"members of group '{group}' would diverge on {what} '{topic}': instances "
                    f"'{first.name}' and '{member.name}' receive different configuration",
                    member.definition.name.location,
                )

    # ---- assembly -----------------------------------------------------------

    def _compute_passthrough(self) -> None:
        """Fill each destination's `passthrough`: the groups whose messages of
        its topic it must relay. AMPS replicates a message received over
        replication only through a destination passing the group it arrived
        from. A destination relays group `G` when it reaches a member that a
        sender in `G` has no single-member destination to: a failover list
        reaches just one of its members, so the others depend on the relay.
        Relaying only then keeps the configuration minimal (plain topics)."""
        direct = {
            (destination.topic, instance.name, destination.target_members[0])
            for instance in self._instances
            for destination in instance.destinations
            if len(destination.target_members) == 1
        }
        group_of = {instance.name: instance.group for instance in self._instances}
        for instance in self._instances:
            # AMPS's rule for queues (its `queue_passthrough` check, lab F8 and
            # F19): an instance receiving a replicated queue from group `G` must
            # pass `G` on *every* destination to another group, queue or not, so
            # acks and ownership transfers reach every copy even when some links
            # are down.
            queue_groups = {
                group_of[edge.source]
                for edge in instance.incoming
                if edge.topic in self._queue_names
            }
            relaying: list[Destination] = []
            for destination in instance.destinations:
                groups = queue_groups - {destination.target_group}
                if destination.topic not in self._queue_names:
                    # Plain topics: relay only where needed (see above).
                    groups |= {
                        group_of[edge.source]
                        for edge in instance.incoming
                        if edge.topic == destination.topic
                        and any(
                            member != edge.source
                            and (destination.topic, edge.source, member) not in direct
                            for member in destination.target_members
                        )
                    }
                relaying.append(replace(destination, passthrough=sorted(groups)))
            instance.destinations = relaying

    def _build(self, topics: list[ResolvedTopic], queues: list[ResolvedQueue]) -> ResolvedSystem:
        groups = [
            ResolvedGroup(name, [self._instances[ix].name for ix in members], is_explicit=True)
            for name, members in self._groups.items()
        ]
        groups += [
            ResolvedGroup(instance.name, [instance.name], is_explicit=False)
            for instance in self._instances
            if instance.definition.group is None
        ]
        is_queue = self._queue_names.__contains__
        instances = [
            ResolvedInstance(
                name=instance.name,
                group=instance.group,
                roles=instance.roles,
                attrs=instance.attrs,
                topics=sorted(name for name in instance.placements if not is_queue(name)),
                destinations=[d for d in instance.destinations if not is_queue(d.topic)],
                incoming=[edge for edge in instance.incoming if not is_queue(edge.topic)],
                sows=instance.sows,
                queues=sorted(name for name in instance.placements if is_queue(name)),
                queue_destinations=[d for d in instance.destinations if is_queue(d.topic)],
                queue_incoming=[edge for edge in instance.incoming if is_queue(edge.topic)],
            )
            for instance in self._instances
        ]
        return ResolvedSystem(topics, queues, groups, instances)


def _check_defaults(role: syntax.RoleDef) -> None:
    for attr in role.attrs:
        if attr.default is not None and _type_name(attr.default) != attr.attr_type.value:
            _fail(
                f"default value for '{role.name.text}.{attr.name.text}' is "
                f"{_type_name(attr.default)}, expected {attr.attr_type.value}",
                attr.name.location,
            )


def _find_attr(role: syntax.RoleDef, name: str) -> syntax.AttrDecl | None:
    return next((decl for decl in role.attrs if decl.name.text == name), None)


def _divergent_topic(a: _InstanceState, b: _InstanceState) -> str:
    """The first (alphabetically) topic on which two group members differ."""
    if placements := a.placements ^ b.placements:
        return min(placements)
    # The same names, but copies of different declarations.
    if copies := [name for name, ix in a.hosts.items() if b.hosts.get(name) != ix]:
        return min(copies)
    if edges := (a.in_view ^ b.in_view) or (a.out_view ^ b.out_view):
        return min(edge[0] for edge in edges)
    return ""


def _statement_location(statement: syntax.TopologyStmt) -> SourceLocation:
    """Where a topology statement's first name is."""
    match statement:
        case syntax.MeshStmt(group):
            return group.location
        case syntax.ReplicateStmt(source=source):
            return source.location
        case syntax.LocalStmt(target) | syntax.SowStmt(target=target):
            return target.location
        case syntax.OwnedStmt(owner=owner):
            return owner.location


