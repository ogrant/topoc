"""Expansion of loops over instances: turns each `for` over a role, group or
instance into concrete topics and queues.

It runs inside resolution, after instances are resolved (the loop needs their
attributes) and before topics are, so the topics it produces go through exactly
the same checks as hand-written ones. Loops over data have already been
expanded by the data expander, which also substituted the data this loop's
topics use. Only the loop variable is substituted here: other `{{Role.attr}}`
placeholders are left for the resolver to interpolate per replication target.
"""

from dataclasses import dataclass, replace
from typing import NoReturn, Protocol

from topoc.dsl import syntax
from topoc.errors import CompileError, SourceLocation
from topoc.model import AttrKey, AttrValue
from topoc.resolve.interpolation import substitute, to_text
from topoc.resolve.names import NameEntry, NameKind
from topoc.resolve.origin import Origin, annotate


class ExpansionContext(Protocol):
    """What expansion needs to know about the resolved declarations."""

    def lookup(self, name: str) -> NameEntry | None:
        """The entry for a declared name (groups included), or `None`."""
        ...

    def instances_of(self, name: syntax.Ident) -> list[str]:
        """The instances a role, group or instance name denotes, in declaration
        order. Raises the same errors as a topology statement naming them."""
        ...

    def attribute(self, instance: str, key: AttrKey) -> AttrValue | None:
        """A resolved attribute of an instance, or `None` if it has none."""
        ...


@dataclass(frozen=True, slots=True)
class ExpandedTopic:
    """A topic to resolve: written by hand (no origin) or generated by a template."""

    topic: syntax.TopicDef
    # The topic's name as written: the template name for a generated topic.
    name_template: str
    origin: Origin | None


@dataclass(frozen=True, slots=True)
class ExpandedQueue:
    """A queue to resolve: written by hand (no origin), or generated by a loop
    over data or over instances."""

    queue: syntax.QueueDef
    # The queue's name as written: the template name for a generated queue.
    name_template: str
    origin: Origin | None


def expand(
    loop: syntax.ForDef,
    context: ExpansionContext,
    outer: Origin | None,
    name_templates: list[str],
) -> list[ExpandedTopic | ExpandedQueue]:
    """The topics and queues of a `for` over instances, iteration by iteration,
    each iteration in body order. `outer` is the iterations of the loops over
    data it was generated in, if any; `name_templates` the names of its items as
    written. Raises `CompileError` for V13-V15 and V17-V19."""
    return _Expansion(loop, context, outer, name_templates).run()


def check_topic_name(name: syntax.Ident) -> None:
    """V18: a topic name must not keep an unresolved `{{...}}`."""
    if "{{" in name.text:
        _fail(f"topic name '{name.text}' contains an unresolved '{{{{...}}}}'", name.location)


def _fail(message: str, at: SourceLocation) -> NoReturn:
    raise CompileError.at(message, at)


class _Expansion:
    """The expansion of one `for` block."""

    def __init__(
        self,
        loop: syntax.ForDef,
        context: ExpansionContext,
        outer: Origin | None,
        name_templates: list[str],
    ) -> None:
        self._loop = loop
        self._context = context
        self._variable = loop.variable.text
        self._outer = outer
        self._name_templates = name_templates

    def _items(self) -> list[syntax.TopicDef | syntax.QueueDef]:
        """The topic and queue templates of the body, in order (the data
        expander leaves only those)."""
        return [
            item for item in self._loop.body if isinstance(item, (syntax.TopicDef, syntax.QueueDef))
        ]

    def run(self) -> list[ExpandedTopic | ExpandedQueue]:
        self._check_variable()
        expanded: list[ExpandedTopic | ExpandedQueue] = []
        for instance in self._instances():
            origin = Origin.within(self._outer, self._loop.location, self._variable, instance)
            for ix, item in enumerate(self._items()):
                name_template = (
                    self._name_templates[ix] if ix < len(self._name_templates) else item.name.text
                )
                if isinstance(item, syntax.QueueDef):
                    queue = self._instantiate_queue(item, instance, origin, name_template)
                    expanded.append(ExpandedQueue(queue, name_template, origin))
                else:
                    bound = self._instantiate(item, instance, origin, name_template)
                    expanded.append(ExpandedTopic(bound, name_template, origin))
        return expanded

    def _check_variable(self) -> None:
        """V13: the variable may not reuse a declared name, so `{{q...}}` and a
        bare `q` in a topology statement are never ambiguous."""
        if (entry := self._context.lookup(self._variable)) is not None:
            _fail(
                f"loop variable '{self._variable}' conflicts with {entry.kind.value} defined at "
                f"line {entry.location.line}, column {entry.location.column}",
                self._loop.variable.location,
            )

    def _refers_to_variable(self, expr: str) -> bool:
        """`{{q}}` or `{{q.Role.attr}}`."""
        return expr == self._variable or expr.startswith(self._variable + ".")

    def _instances(self) -> list[str]:
        """V14: the instances the domain denotes, in declaration order."""
        domain = self._loop.domain
        if not isinstance(domain, syntax.Ident):
            _fail(
                "an inline list or a context path is expanded before instances are resolved",
                self._loop.location,
            )
        entry = self._context.lookup(domain.text)
        if entry is None:
            _fail(f"unknown name '{domain.text}'", domain.location)
        match entry.kind:
            case NameKind.TOPIC | NameKind.QUEUE | NameKind.LIST | NameKind.TOPOLOGY:
                _fail(
                    f"'{domain.text}' is a {entry.kind.value}; a 'for' iterates over a list, "
                    "role, group or instance",
                    domain.location,
                )
            case NameKind.ROLE | NameKind.GROUP | NameKind.INSTANCE:
                return self._context.instances_of(domain)

    def _instantiate(
        self, topic: syntax.TopicDef, instance: str, origin: Origin, name_template: str
    ) -> syntax.TopicDef:
        """One topic of one iteration. Errors are annotated with the iteration."""
        try:
            name = self._bind_topic_name(topic.name, instance, "topic")
            check_topic_name(name)
        except CompileError as error:
            raise annotate(error, origin, "topic", name_template) from error
        try:
            topology = None
            if topic.topology is not None:
                topology = [self._bind_statement(s, instance) for s in topic.topology]
            return syntax.TopicDef(name, topic.definition, topology)
        except CompileError as error:
            raise annotate(error, origin, "topic", name.text) from error

    def _instantiate_queue(
        self, queue: syntax.QueueDef, instance: str, origin: Origin, name_template: str
    ) -> syntax.QueueDef:
        """One queue of one iteration: its name like a topic's (V19, since a
        queue reading its own name fits its definition's pattern), its sources
        and strings substituted, and a bare variable in its topology the
        instance. Errors are annotated with the iteration."""
        try:
            name = self._bind_topic_name(queue.name, instance, "queue")
        except CompileError as error:
            raise annotate(error, origin, "queue", name_template) from error
        try:
            source = queue.source
            if isinstance(source, syntax.QueueTopics):
                source = syntax.QueueTopics(
                    [self._bind_reference(s, instance) for s in source.sources],
                    None
                    if source.publish_to is None
                    else self._bind_reference(source.publish_to, instance),
                )
            ordering: syntax.QueueOrdering | None
            match queue.ordering:
                case syntax.Priority(path):
                    ordering = syntax.Priority(self._bind_string(path, instance))
                case syntax.Barrier(text):
                    ordering = syntax.Barrier(self._bind_string(text, instance))
                case None:
                    ordering = None
            return replace(
                queue,
                name=name,
                source=source,
                filter=None if queue.filter is None else self._bind_string(queue.filter, instance),
                ordering=ordering,
                topology=[self._bind_statement(s, instance) for s in queue.topology],
            )
        except CompileError as error:
            raise annotate(error, origin, "queue", name.text) from error

    def _bind_reference(self, name: syntax.Ident, instance: str) -> syntax.Ident:
        """A topic named by reference (a queue's source): the variable denotes
        its instance, and `{{q}}` / `{{q.Role.attr}}` in a quoted name are
        substituted."""
        if name.text == self._variable:
            return self._bind_name(name, instance)
        bound = substitute(
            name.text, lambda expr: self._resolve_reference(expr, instance, name.location)
        )
        return syntax.Ident(name.text if bound is None else bound, name.location)

    def _bind_statement(self, statement: syntax.TopologyStmt, instance: str) -> syntax.TopologyStmt:
        match statement:
            case syntax.MeshStmt(group):
                return syntax.MeshStmt(self._bind_name(group, instance))
            case syntax.ReplicateStmt(source, target, where, two_way):
                return syntax.ReplicateStmt(
                    self._bind_name(source, instance),
                    self._bind_name(target, instance),
                    None if where is None else self._bind_string(where, instance),
                    two_way,
                )
            case syntax.LocalStmt(target):
                return syntax.LocalStmt(self._bind_name(target, instance))
            case syntax.SowStmt(target, durability):
                return syntax.SowStmt(
                    self._bind_name(target, instance), self._bind_durability(durability, instance)
                )
            case syntax.OwnedStmt(owner, statements):
                return syntax.OwnedStmt(
                    self._bind_name(owner, instance),
                    [self._bind_statement(inner, instance) for inner in statements],
                )

    def _bind_durability(self, durability: syntax.Durability, instance: str) -> syntax.Durability:
        if isinstance(durability, syntax.PersistentDurability):
            return syntax.PersistentDurability(self._bind_string(durability.file, instance))
        return durability

    def _bind_name(self, name: syntax.Ident, instance: str) -> syntax.Ident:
        """The variable used as a topology name denotes its instance."""
        if name.text != self._variable:
            return name
        return syntax.Ident(instance, name.location)

    def _bind_string(self, string: syntax.StringLit, instance: str) -> syntax.StringLit:
        bound = substitute(
            string.value,
            lambda expr: self._resolve_reference(expr, instance, string.location),
        )
        return syntax.StringLit(string.value if bound is None else bound, string.location)

    def _bind_topic_name(self, name: syntax.Ident, instance: str, what: str) -> syntax.Ident:
        """Substitute the variable in a topic name (V19): each value must be one
        non-empty segment without `/`, so every placeholder stays within one
        segment of the name and lines up with the definition's name pattern."""

        def value_of(expr: str) -> str | None:
            value = self._resolve_reference(expr, instance, name.location)
            if value is not None and (value == "" or "/" in value):
                problem = "which is empty" if value == "" else "which contains '/'"
                _fail(
                    f"'{{{{{expr}}}}}' in a {what} name expands to '{value}', {problem}",
                    name.location,
                )
            return value

        bound = substitute(name.text, value_of)
        return syntax.Ident(name.text if bound is None else bound, name.location)

    def _resolve_reference(self, expr: str, instance: str, at: SourceLocation) -> str | None:
        """The value of a `{{q}}` or `{{q.Role.attr}}` expression for one
        iteration, or `None` if `expr` does not reference the loop variable
        (V17). Other placeholders stay for the resolver."""
        if expr == self._variable:
            return instance
        if not self._refers_to_variable(expr):
            return None
        qualified = expr[len(self._variable) + 1 :]
        role, dot, attr = qualified.rpartition(".")
        if not dot:
            _fail(
                f"'{{{{{expr}}}}}' must be '{{{{{self._variable}}}}}' or "
                f"'{{{{{self._variable}.Role.attr}}}}'",
                at,
            )
        value = self._context.attribute(instance, AttrKey(role, attr))
        if value is None:
            _fail(f"'{{{{{expr}}}}}': instance '{instance}' has no attribute '{qualified}'", at)
        return to_text(value)
