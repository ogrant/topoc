"""What every name in a `.topo` source refers to: each entity's declarations,
every occurrence of it, and what hovering it shows. Go to definition, find
references and hover all read it.

It is built from the syntax tree alone, without resolving: roles, attributes,
instances, groups, topics, queues, lists, topology blocks, context fields and
types, and loop variables, scoped to their `for`. A path is followed segment by
segment: `loc.port_base` through the context's types, `{{q.Quoting.key}}`
through a role's attributes. Names generated by a loop (`"Quoting.{{loc}}"`)
link only through their placeholders.
"""

from collections.abc import Callable
from dataclasses import dataclass, field
from enum import Enum

from topoc.context import Context, Data, ObjectData
from topoc.dsl import syntax
from topoc.errors import SourceLocation
from topoc.lsp.text import Position, Span, block_span, start_of, token_span
from topoc.queue import AtLeastOnce

# An entity's identity: its kind, then what names it, e.g. `("attribute", "R",
# "key")`, or a loop variable's position.
type Key = tuple[str, ...]


@dataclass(frozen=True, slots=True)
class Occurrence:
    span: Span
    key: Key
    declaration: bool


@dataclass(slots=True)
class Entity:
    key: Key
    # Where it is declared (several for a group, or a name several topic
    # declarations share).
    declarations: list[Span]
    # Markdown.
    hover: str


@dataclass(slots=True)
class Index:
    entities: dict[Key, Entity]
    # By span start, so an occurrence reached twice (a topology block's
    # statements, inlined where used) is kept once.
    occurrences: dict[Position, Occurrence]

    def at(self, position: Position) -> Occurrence | None:
        """The innermost occurrence under `position` (a placeholder inside a
        quoted name, not the name), or one ending there."""
        inside = [
            o
            for o in self.occurrences.values()
            if o.span.start <= position < o.span.end and o.span.start.line == position.line
        ]
        if inside:
            return max(inside, key=lambda o: o.span.start)
        return next((o for o in self.occurrences.values() if o.span.end == position), None)

    def references(self, key: Key) -> list[Occurrence]:
        return sorted(
            (o for o in self.occurrences.values() if o.key == key),
            key=lambda o: o.span.start,
        )


def build_index(file: syntax.SourceFile, source: str, context: Context | None) -> Index:
    """The index of `file`, parsed from `source`; `context`, the data found for
    it if any, adds a loop variable's values to its hover."""
    return _Builder(file, source, context).build()


class _Kind(Enum):
    """What a loop variable stands for, which decides what its path reaches."""

    VALUE = "value"  # a list item or map key: no fields
    INDEX = "index"  # a count over an integer
    RECORD = "record"  # a map key whose value is a record: its fields
    MAP_VALUE = "map value"  # a map's value, of `type_expr`
    INSTANCE = "instance"  # an instance: `Role.attr`


@dataclass(frozen=True, slots=True)
class _Var:
    key: Key
    kind: _Kind
    # The record's type (`RECORD`) or the value's (`MAP_VALUE`).
    type_expr: syntax.TypeExpr | None


# The loop variables in scope, innermost last.
type _Scope = tuple[tuple[str, _Var], ...]

# The span of the segments `first` through `last` of an expression.
type _SpanOf = Callable[[int, int], Span]


@dataclass(slots=True)
class _Declared:
    """What pass one learns about the declarations, for links and hovers."""

    roles: dict[str, syntax.RoleDef] = field(default_factory=dict)
    instances: dict[str, list[syntax.InstanceDef]] = field(default_factory=dict)
    groups: dict[str, list[str]] = field(default_factory=dict)
    topics: dict[str, list[syntax.TopicDef]] = field(default_factory=dict)
    queues: dict[str, list[syntax.QueueDef]] = field(default_factory=dict)
    lists: dict[str, syntax.ListDef] = field(default_factory=dict)
    blocks: dict[str, syntax.TopologyDef] = field(default_factory=dict)
    fields: dict[str, syntax.FieldDecl] = field(default_factory=dict)
    types: dict[str, syntax.TypeDef] = field(default_factory=dict)


class _Builder:
    def __init__(self, file: syntax.SourceFile, source: str, context: Context | None) -> None:
        self._file = file
        self._source = source
        self._lines = source.split("\n")
        self._context = context
        self._declared = _Declared()
        self._index = Index({}, {})

    # ---- entities and occurrences -------------------------------------------

    def _entity(self, key: Key, hover: str) -> Entity:
        entity = self._index.entities.get(key)
        if entity is None:
            entity = Entity(key, [], hover)
            self._index.entities[key] = entity
        return entity

    def _declare(self, key: Key, span: Span, hover: str) -> None:
        entity = self._entity(key, hover)
        if span not in entity.declarations:
            entity.declarations.append(span)
        self._index.occurrences[span.start] = Occurrence(span, key, True)

    def _refer(self, key: Key, span: Span) -> None:
        if key in self._index.entities and span.start not in self._index.occurrences:
            self._index.occurrences[span.start] = Occurrence(span, key, False)

    def _quoted(self, ident: syntax.Ident) -> bool:
        start = start_of(ident.location)
        line = self._lines[start.line] if start.line < len(self._lines) else ""
        return line[start.column : start.column + 1] == '"'

    def _segment(self, location: SourceLocation, offset: int, length: int) -> Span:
        start = start_of(location)
        return Span(
            Position(start.line, start.column + offset),
            Position(start.line, start.column + offset + length),
        )

    # ---- pass one: declarations ---------------------------------------------

    def build(self) -> Index:
        for definition in self._file.definitions:
            self._collect(definition)
        self._declare_all()
        self._namespace = self._names()
        for definition in self._file.definitions:
            self._walk(definition, ())
        for block_use in self._file.block_uses:
            block = block_use.block
            self._refer(("topology", block.text), token_span(self._lines, block.location))
            for argument in block_use.arguments:
                self._refer(
                    ("parameter", block.text, argument.parameter.text),
                    token_span(self._lines, argument.parameter.location),
                )
        return self._index

    def _collect(self, definition: syntax.Definition | syntax.ForItem) -> None:
        declared = self._declared
        match definition:
            case syntax.RoleDef(name=name):
                declared.roles[name.text] = definition
            case syntax.InstanceDef(name=name, group=group):
                declared.instances.setdefault(name.text, []).append(definition)
                if group is not None:
                    declared.groups.setdefault(group.text, []).append(name.text)
            case syntax.TopicDef(name=name):
                declared.topics.setdefault(name.text, []).append(definition)
            case syntax.QueueDef(name=name):
                declared.queues.setdefault(name.text, []).append(definition)
            case syntax.ListDef(name=name):
                declared.lists[name.text] = definition
            case syntax.TopologyDef(name=name):
                declared.blocks[name.text] = definition
            case syntax.ContextDef(types=types, fields=fields):
                declared.types.update((t.name.text, t) for t in types)
                declared.fields.update((f.name.text, f) for f in fields)
            case syntax.ForDef(body=body):
                for item in body:
                    self._collect(item)

    def _declare_all(self) -> None:
        declared = self._declared
        span = self._name_span
        for name, role in declared.roles.items():
            self._declare(("role", name), span(role.name), self._role_hover(role))
            for attr in role.attrs:
                self._declare(
                    ("attribute", name, attr.name.text),
                    span(attr.name),
                    _code(f"attr {name}.{_attr_text(attr)}") + f"\n\nAttribute of role `{name}`.",
                )
        for name, instances in declared.instances.items():
            for instance in instances:
                self._declare(("instance", name), span(instance.name), self._instance_hover(name))
        for name, members in declared.groups.items():
            hover = _code(f"group {name}") + "\n\nMembers: " + ", ".join(f"`{m}`" for m in members)
            for instances in declared.instances.values():
                for instance in instances:
                    if instance.group is not None and instance.group.text == name:
                        self._declare(("group", name), span(instance.group), hover)
        for name, topics in declared.topics.items():
            for topic in topics:
                self._declare(("topic", name), span(topic.name), self._topic_hover(name))
        for name, queues in declared.queues.items():
            for queue in queues:
                self._declare(("queue", name), span(queue.name), self._queue_hover(name))
        for name, items in declared.lists.items():
            values = ", ".join(item.value for item in items.items)
            self._declare(("list", name), span(items.name), _code(f"list {name} [{values}]"))
        for name, block in declared.blocks.items():
            text = self._text(block_span(self._lines, block.name.location))
            self._declare(("topology", name), span(block.name), _code(f"topology {text}"))
            for param in block.params:
                self._declare(
                    ("parameter", name, param.name.text),
                    span(param.name),
                    _code(f"{param.name.text}: {param.kind.value}")
                    + f"\n\nParameter of topology block `{name}`.",
                )
        for name, type_def in declared.types.items():
            body = "  ".join(_field_text(f) for f in type_def.fields)
            self._declare(("type", name), span(type_def.name), _code(f"type {name} {{ {body} }}"))
            for decl in type_def.fields:
                self._declare(
                    ("field", name, decl.name.text),
                    span(decl.name),
                    _code(_field_text(decl)) + f"\n\nField of context type `{name}`.",
                )
        for name, decl in declared.fields.items():
            self._declare(
                ("context", name),
                span(decl.name),
                _code(_field_text(decl)) + f"\n\nContext field, written `@{name}`.",
            )

    def _names(self) -> dict[str, Key]:
        """The flat namespace: what a bare name in a topology statement or a
        `for` domain denotes."""
        names: dict[str, Key] = {}
        declared = self._declared
        for kind, table in (
            ("topic", declared.topics),
            ("queue", declared.queues),
            ("list", declared.lists),
            ("topology", declared.blocks),
            ("group", declared.groups),
            ("instance", declared.instances),
            ("role", declared.roles),
        ):
            for name in table:
                names[name] = (kind, name)
        return names

    def _name_span(self, ident: syntax.Ident) -> Span:
        return token_span(self._lines, ident.location)

    # ---- pass two: references -----------------------------------------------

    def _walk(self, definition: syntax.Definition | syntax.ForItem, scope: _Scope) -> None:
        match definition:
            case syntax.RoleDef():
                pass
            case syntax.InstanceDef(name=name, roles=roles, group=group, attrs=attrs):
                self._placeholders(name, scope)
                for role in roles:
                    self._refer(("role", role.text), self._name_span(role))
                if group is not None:
                    self._placeholders(group, scope)
                for assign in attrs:
                    self._attr_assign(assign, scope)
            case syntax.TopicDef(name=name, topology=topology):
                self._placeholders(name, scope)
                for statement in topology or []:
                    self._statement(statement, scope)
            case syntax.QueueDef():
                self._queue(definition, scope)
            case syntax.ListDef():
                pass
            case syntax.TopologyDef(name=name, params=params, statements=statements):
                # Its parameters are in scope in its statements, as names.
                block_scope: _Scope = tuple(
                    (
                        param.name.text,
                        _Var(("parameter", name.text, param.name.text), _Kind.VALUE, None),
                    )
                    for param in params
                )
                for statement in statements:
                    self._statement(statement, block_scope)
            case syntax.ContextDef(types=types, fields=fields):
                for decl in [*fields, *(f for t in types for f in t.fields)]:
                    self._type_refs(decl.type_expr)
            case syntax.ForDef():
                self._for(definition, scope)

    def _attr_assign(self, assign: syntax.AttrAssign, scope: _Scope) -> None:
        role, attr = assign.role.text, assign.attr.text
        location = assign.role.location
        self._refer(("role", role), self._segment(location, 0, len(role)))
        self._refer(("attribute", role, attr), self._segment(location, len(role) + 1, len(attr)))
        if isinstance(assign.value, syntax.Placeholder):
            self._bare_placeholder(assign.value_location, scope)
        elif isinstance(assign.value, str):
            self._string_placeholders(assign.value_location, scope)

    def _queue(self, queue: syntax.QueueDef, scope: _Scope) -> None:
        self._placeholders(queue.name, scope)
        if isinstance(queue.source, syntax.QueueTopics):
            for source in [*queue.source.sources, *filter(None, [queue.source.publish_to])]:
                self._name(source, scope)
        strings = [queue.filter]
        match queue.ordering:
            case syntax.Priority(path=text) | syntax.Barrier(filter=text):
                strings.append(text)
        for string in strings:
            if string is not None:
                self._string_placeholders(string.location, scope)
        for statement in queue.topology:
            self._statement(statement, scope)

    def _statement(self, statement: syntax.TopologyStmt, scope: _Scope) -> None:
        match statement:
            case syntax.MeshStmt(group=name) | syntax.LocalStmt(target=name):
                self._name(name, scope)
            case syntax.ReplicateStmt(source=source, target=target, filter=where):
                self._name(source, scope)
                self._name(target, scope)
                if where is not None:
                    self._string_placeholders(where.location, scope)
            case syntax.SowStmt(target=target, durability=durability):
                self._name(target, scope)
                if isinstance(durability, syntax.PersistentDurability):
                    self._string_placeholders(durability.file.location, scope)
            case syntax.OwnedStmt(owner=owner, statements=inner):
                self._name(owner, scope)
                for nested in inner:
                    self._statement(nested, scope)

    def _name(self, ident: syntax.Ident, scope: _Scope) -> None:
        """A name in a topology statement or a queue's sources: a bare
        instance-loop variable, a declared name, or a quoted name whose
        placeholders are the links."""
        if self._quoted(ident):
            if "{{" in ident.text:
                self._placeholders(ident, scope)
            elif (key := self._namespace.get(ident.text)) is not None:
                self._refer(key, self._name_span(ident))
            return
        var = _lookup(scope, ident.text)
        if var is not None:
            self._refer(var.key, self._name_span(ident))
        elif (key := self._namespace.get(ident.text)) is not None:
            self._refer(key, self._name_span(ident))

    def _type_refs(self, type_expr: syntax.TypeExpr) -> None:
        if type_expr.record is not None:
            self._refer(("type", type_expr.record.text), self._name_span(type_expr.record))
        if type_expr.inner is not None:
            self._type_refs(type_expr.inner)

    # ---- loops --------------------------------------------------------------

    def _for(self, loop: syntax.ForDef, scope: _Scope) -> None:
        domain = loop.domain
        type_expr: syntax.TypeExpr | None = None
        over_instances = False
        match domain:
            case syntax.ContextPath(path=path, location=location):
                type_expr = self._expr_at(f"@{path}", location, 0, scope)
            case syntax.Ident(text=text, location=location):
                head = text.split(".", 1)[0]
                if _lookup(scope, head) is not None:
                    type_expr = self._expr_at(text, location, 0, scope)
                elif (key := self._namespace.get(text)) is not None:
                    self._refer(key, self._name_span(domain))
                    over_instances = key[0] in ("role", "group", "instance")
            case _:
                pass
        description = f"for {_loop_variables(loop)} in {_domain_text(domain)}"
        values = self._values(domain)
        hover = _code(description) + ("" if values is None else f"\n\nValues: {values}")
        kind, item_type = _element(type_expr, two_variables=loop.value is not None)
        if over_instances:
            kind = _Kind.INSTANCE
        variable_key = (
            "loop",
            str(loop.variable.location.line),
            str(loop.variable.location.column),
        )
        self._declare(variable_key, self._name_span(loop.variable), hover)
        inner = (*scope, (loop.variable.text, _Var(variable_key, kind, item_type)))
        if loop.value is not None:
            value_key = ("loop", str(loop.value.location.line), str(loop.value.location.column))
            self._declare(value_key, self._name_span(loop.value), hover)
            value_type = type_expr.inner if type_expr is not None else None
            inner = (*inner, (loop.value.text, _Var(value_key, _Kind.MAP_VALUE, value_type)))
        for item in loop.body:
            self._walk(item, inner)

    def _values(self, domain: syntax.ForDomain) -> str | None:
        """The values a `for` over `domain` takes, when known without
        iterating: a list's items, a top-level context path's data, a role's or
        group's declared instances."""
        match domain:
            case list():
                return _shown([item.value for item in domain])
            case syntax.ContextPath(path=path):
                return None if self._context is None else _data_values(self._context, path)
            case syntax.Ident(text=text):
                declared = self._declared
                if text in declared.lists:
                    return _shown([item.value for item in declared.lists[text].items])
                if text in declared.groups:
                    return _shown(declared.groups[text])
                if text in declared.roles:
                    return _shown(
                        [
                            name
                            for name, instances in declared.instances.items()
                            if any(r.text == text for i in instances for r in i.roles)
                        ]
                    )
        return None

    # ---- paths and placeholders ---------------------------------------------

    def _expr_at(
        self, expr: str, location: SourceLocation, offset: int, scope: _Scope
    ) -> syntax.TypeExpr | None:
        """Link the expression `expr`, which starts `offset` code points after
        `location`; return the context type it reaches, if any."""
        segments = expr.split(".")
        starts = []
        position = offset
        for segment in segments:
            starts.append(position)
            position += len(segment) + 1

        def span(first: int, last: int) -> Span:
            end = starts[last] + len(segments[last])
            return self._segment(location, starts[first], end - starts[first])

        head = segments[0]
        if head.startswith("@"):
            name = head[1:]
            decl = self._declared.fields.get(name)
            self._refer(("context", name), span(0, 0))
            if decl is None:
                return None
            return self._fields(decl.type_expr, segments, 1, span)
        var = _lookup(scope, head)
        if var is not None:
            self._refer(var.key, span(0, 0))
            if var.kind is _Kind.INSTANCE and len(segments) >= 3:
                self._role_attribute(segments, 1, span)
                return None
            if var.kind in (_Kind.RECORD, _Kind.MAP_VALUE) and var.type_expr is not None:
                return self._fields(var.type_expr, segments, 1, span)
            return None
        if len(segments) >= 2:
            self._role_attribute(segments, 0, span)
        elif (key := self._namespace.get(head)) is not None:
            self._refer(key, span(0, 0))
        return None

    def _role_attribute(self, segments: list[str], first: int, span: _SpanOf) -> None:
        """`Role.attr` from `segments[first]`, the role possibly dotted."""
        role = ".".join(segments[first:-1])
        if role in self._declared.roles:
            self._refer(("role", role), span(first, len(segments) - 2))
            last = len(segments) - 1
            self._refer(("attribute", role, segments[last]), span(last, last))

    def _fields(
        self, type_expr: syntax.TypeExpr, segments: list[str], first: int, span: _SpanOf
    ) -> syntax.TypeExpr | None:
        """Follow `segments[first:]` as record fields from `type_expr`."""
        current: syntax.TypeExpr | None = type_expr
        for index in range(first, len(segments)):
            if current is None or current.kind is not syntax.TypeKind.RECORD:
                return None
            assert current.record is not None
            record = self._declared.types.get(current.record.text)
            decl = None if record is None else _field(record, segments[index])
            if decl is None:
                return None
            self._refer(("field", current.record.text, segments[index]), span(index, index))
            current = decl.type_expr
        return current

    def _placeholders(self, ident: syntax.Ident, scope: _Scope) -> None:
        """The placeholders of a name, quoted or not."""
        if self._quoted(ident):
            self._string_placeholders(ident.location, scope)

    def _string_placeholders(self, location: SourceLocation, scope: _Scope) -> None:
        """Each `{{...}}` in the string literal starting at `location`."""
        token = token_span(self._lines, location)
        line = self._lines[token.start.line]
        text = line[token.start.column : token.end.column]
        search = 0
        while (opening := text.find("{{", search)) >= 0:
            closing = text.find("}}", opening)
            if closing < 0:
                return
            self._expr_in(text, opening + 2, closing, location, scope)
            search = closing + 2

    def _bare_placeholder(self, location: SourceLocation, scope: _Scope) -> None:
        """A bare `{{path}}` attribute value at `location`."""
        token = token_span(self._lines, location)
        text = self._lines[token.start.line][token.start.column : token.end.column]
        if text.startswith("{{") and text.endswith("}}"):
            self._expr_in(text, 2, len(text) - 2, location, scope)

    def _expr_in(
        self, text: str, start: int, end: int, location: SourceLocation, scope: _Scope
    ) -> None:
        raw = text[start:end]
        expr = raw.strip()
        if expr:
            self._expr_at(expr, location, start + len(raw) - len(raw.lstrip()), scope)

    # ---- hovers ---------------------------------------------------------------

    def _text(self, span: Span) -> str:
        lines = self._lines[span.start.line : span.end.line + 1]
        if not lines:
            return ""
        lines[-1] = lines[-1][: span.end.column]
        lines[0] = lines[0][span.start.column :]
        return "\n".join(lines)

    def _role_hover(self, role: syntax.RoleDef) -> str:
        attrs = "\n".join(f"  attr {_attr_text(attr)}" for attr in role.attrs)
        body = f" {{\n{attrs}\n}}" if attrs else " { }"
        carriers = [
            name
            for name, instances in self._declared.instances.items()
            if any(r.text == role.name.text for i in instances for r in i.roles)
        ]
        carried = "Carried by: " + (", ".join(f"`{c}`" for c in carriers) or "no instance")
        return _code(f"role {role.name.text}{body}") + "\n\n" + carried

    def _instance_hover(self, name: str) -> str:
        instance = self._declared.instances[name][0]
        lines = []
        if instance.roles:
            lines.append("  roles [" + ", ".join(r.text for r in instance.roles) + "]")
        if instance.group is not None:
            lines.append(f"  group {instance.group.text}")
        lines += [
            f"  attr {a.role.text}.{a.attr.text} {_value_text(a.value)}" for a in instance.attrs
        ]
        body = "\n".join(lines)
        text = _code(f"instance {name} {{\n{body}\n}}" if body else f"instance {name} {{ }}")
        if "{{" in name:
            text += "\n\nDeclared by a `for`: one instance per iteration."
        elif instance.group is None:
            text += f"\n\nAlone in group `{name}`."
        return text

    def _topic_hover(self, name: str) -> str:
        topics = self._declared.topics[name]
        definitions = sorted({t.definition.text for t in topics if t.definition is not None})
        text = _code(f"topic {name}")
        if definitions:
            text += "\n\nDefinition: " + ", ".join(f"`{d}`" for d in definitions)
        if len(topics) > 1:
            text += f"\n\n{len(topics)} declarations, each placing its own copy."
        return text

    def _queue_hover(self, name: str) -> str:
        queue = self._declared.queues[name][0]
        match queue.source:
            case syntax.QueueTopics(sources=sources):
                source = "from " + ", ".join(s.text for s in sources)
            case syntax.QueueOwnName(definition=definition):
                source = f"definition {definition.text}"
        delivery = "at_least_once" if isinstance(queue.delivery, AtLeastOnce) else "at_most_once"
        return _code(f"queue {name}") + f"\n\n`{source}`, delivered `{delivery}`."


def _lookup(scope: _Scope, name: str) -> _Var | None:
    return next((var for bound, var in reversed(scope) if bound == name), None)


def _element(
    type_expr: syntax.TypeExpr | None, *, two_variables: bool
) -> tuple[_Kind, syntax.TypeExpr | None]:
    """What a `for` variable over a value of `type_expr` stands for."""
    if type_expr is None:
        return _Kind.VALUE, None
    match type_expr.kind:
        case syntax.TypeKind.INT:
            return _Kind.INDEX, None
        case syntax.TypeKind.MAP if not two_variables and type_expr.inner is not None:
            if type_expr.inner.kind is syntax.TypeKind.RECORD:
                return _Kind.RECORD, type_expr.inner
    return _Kind.VALUE, None


def _field(record: syntax.TypeDef, name: str) -> syntax.FieldDecl | None:
    return next((f for f in record.fields if f.name.text == name), None)


def _data_values(context: Context, path: str) -> str | None:
    """The values a `for` over the context path `path` takes."""
    data: Data = ObjectData(context.members)
    for segment in path.split("."):
        if not isinstance(data, ObjectData):
            return None
        found = next((value for name, value in data.members if name == segment), None)
        if found is None:
            return None
        data = found
    match data:
        case list():
            return _shown([str(item) for item in data])
        case ObjectData(members=members):
            return _shown([name for name, _ in members])
        case bool():
            return None
        case int():
            return "none" if data <= 0 else f"0 to {data - 1}"
    return None


def _shown(values: list[str]) -> str:
    """At most ten values, as a hover lists them."""
    if not values:
        return "none"
    shown = ", ".join(f"`{value}`" for value in values[:10])
    return shown if len(values) <= 10 else f"{shown} and {len(values) - 10} more"


def _code(text: str) -> str:
    return f"```topo\n{text}\n```"


def _type_text(type_expr: syntax.TypeExpr) -> str:
    match type_expr.kind:
        case syntax.TypeKind.RECORD:
            assert type_expr.record is not None
            return type_expr.record.text
        case syntax.TypeKind.LIST:
            assert type_expr.inner is not None
            return f"{_type_text(type_expr.inner)}[]"
        case syntax.TypeKind.MAP:
            assert type_expr.inner is not None
            return f"{_type_text(type_expr.inner)}[string]"
        case kind:
            return str(kind.value)


def _field_text(decl: syntax.FieldDecl) -> str:
    return f"{decl.name.text}: {_type_text(decl.type_expr)}"


def _value_text(value: syntax.Literal | syntax.Placeholder) -> str:
    match value:
        case syntax.Placeholder(expr=expr):
            return f"{{{{{expr}}}}}"
        case bool():
            return "true" if value else "false"
        case int():
            return str(value)
        case str():
            return f'"{value}"'


def _attr_text(attr: syntax.AttrDecl) -> str:
    text = f"{attr.name.text}: {attr.attr_type.value}"
    return text if attr.default is None else f"{text} = {_value_text(attr.default)}"


def _loop_variables(loop: syntax.ForDef) -> str:
    return loop.variable.text if loop.value is None else f"{loop.variable.text}, {loop.value.text}"


def _domain_text(domain: syntax.ForDomain) -> str:
    match domain:
        case syntax.Ident(text=text):
            return text
        case syntax.ContextPath():
            return str(domain)
        case _:
            return "[" + ", ".join(item.value for item in domain) + "]"
